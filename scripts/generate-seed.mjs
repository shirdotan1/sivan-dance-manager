// Generates supabase/seed.sql from the demo data so the real app looks
// identical to the demo on day one.
//
//   node scripts/generate-seed.mjs
//
// Node ≥ 22.18 strips the TypeScript types from the imported .ts files.
// Short demo keys become stable UUIDs, so re-generating gives the same IDs.

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { lessons, projects, songs, spaces } from "../src/data/demo.ts";
import { PALETTE } from "../src/lib/palette.ts";

/** Deterministic UUID (v5-style layout) from a namespaced demo key. */
function uuid(kind, key) {
  const h = createHash("sha1").update(`sivan-dance:${kind}:${key}`).digest("hex");
  const variant = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

/** SQL literal: NULL, numbers, booleans, or a safely quoted string. */
function lit(v) {
  if (v === undefined || v === null) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replaceAll("'", "''")}'`;
}

function insert(table, columns, rows) {
  if (rows.length === 0) return "";
  const values = rows.map((r) => `  (${r.map(lit).join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values};\n\n`;
}

// Distinct, increasing created_at values so lists keep the demo's order
// (the app orders pools, groups, songs and projects by creation time).
const SEED_EPOCH = Date.parse("2026-09-01T08:00:00Z");
let tick = 0;
const createdAt = () => new Date(SEED_EPOCH + tick++ * 1000).toISOString();

let colorIndex = 0;
const nextColor = () => PALETTE[colorIndex++ % PALETTE.length];

const rows = {
  spaces: [], students: [], groups: [], group_members: [], songs: [],
  lessons: [], lesson_participants: [], lesson_songs: [],
  projects: [], project_participants: [], sessions: [], session_payments: [], session_songs: [],
  media_items: [],
};

spaces.forEach((space, i) => {
  rows.spaces.push([space.id, space.name, space.kind, space.description, i]);
  for (const st of space.students) rows.students.push([uuid("student", st.id), space.id, st.name, st.phone, createdAt()]);
  for (const g of space.groups ?? []) {
    rows.groups.push([uuid("group", g.id), space.id, g.name, nextColor(), createdAt()]);
    for (const sid of g.studentIds) rows.group_members.push([uuid("group", g.id), uuid("student", sid)]);
  }
});

for (const s of songs) {
  rows.songs.push([uuid("song", s.id), s.kind ?? "song", s.title, s.artist, s.style, s.link, s.note, s.titleLang, s.artistLang, createdAt()]);
}

for (const l of lessons) {
  const id = uuid("lesson", l.id);
  rows.lessons.push([id, l.spaceId, l.groupId ? uuid("group", l.groupId) : null, l.date, l.time, l.notes]);
  for (const sid of l.participantIds) rows.lesson_participants.push([id, uuid("student", sid)]);
  l.materialIds.forEach((sid, pos) => rows.lesson_songs.push([id, uuid("song", sid), pos]));
  l.media.forEach((m, pos) => rows.media_items.push([uuid("media", m.id), id, null, m.kind, m.caption, pos]));
}

for (const p of projects) {
  const pid = uuid("project", p.id);
  rows.projects.push([pid, "private-lessons", p.name, p.type, uuid("song", p.mainMaterialId), nextColor(), createdAt()]);
  for (const sid of p.participantIds) rows.project_participants.push([pid, uuid("student", sid)]);
  for (const s of p.sessions) {
    const sid = uuid("session", `${p.id}/${s.id}`);
    rows.sessions.push([sid, pid, s.date, s.time, s.notes]);
    for (const pay of s.payments) rows.session_payments.push([sid, uuid("student", pay.studentId), pay.amount, pay.paid]);
    s.materialIds.forEach((song, pos) => rows.session_songs.push([sid, uuid("song", song), pos]));
    s.media.forEach((m, pos) => rows.media_items.push([uuid("media", m.id), null, sid, m.kind, m.caption, pos]));
  }
}

const sql =
  `-- Generated by scripts/generate-seed.mjs from src/data/demo.ts — do not edit by hand.\n` +
  `--\n` +
  `-- !!! WARNING — ONE-TIME SETUP ONLY !!!\n` +
  `-- Run this ONCE, right after schema.sql, on a NEW, EMPTY Supabase project.\n` +
  `-- It inserts the demo data with fixed ids. NEVER run it again once real\n` +
  `-- data has been entered: it would fail on existing ids or mix demo rows into\n` +
  `-- real data. (Re-seeding means re-running schema.sql, which DELETES ALL DATA.)\n\n` +
  `begin;\n\n` +
  insert("spaces", ["id", "name", "kind", "description", "position"], rows.spaces) +
  insert("students", ["id", "space_id", "name", "phone", "created_at"], rows.students) +
  insert("groups", ["id", "space_id", "name", "color", "created_at"], rows.groups) +
  insert("group_members", ["group_id", "student_id"], rows.group_members) +
  insert("songs", ["id", "kind", "title", "artist", "style", "link", "note", "title_lang", "artist_lang", "created_at"], rows.songs) +
  insert("lessons", ["id", "space_id", "group_id", "date", "time", "notes"], rows.lessons) +
  insert("lesson_participants", ["lesson_id", "student_id"], rows.lesson_participants) +
  insert("lesson_songs", ["lesson_id", "song_id", "position"], rows.lesson_songs) +
  insert("projects", ["id", "space_id", "name", "type", "main_song_id", "color", "created_at"], rows.projects) +
  insert("project_participants", ["project_id", "student_id"], rows.project_participants) +
  insert("sessions", ["id", "project_id", "date", "time", "notes"], rows.sessions) +
  insert("session_payments", ["session_id", "student_id", "amount", "paid"], rows.session_payments) +
  insert("session_songs", ["session_id", "song_id", "position"], rows.session_songs) +
  insert("media_items", ["id", "lesson_id", "session_id", "kind", "caption", "position"], rows.media_items) +
  `commit;\n`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(Object.entries(rows).map(([t, r]) => `${t}: ${r.length}`).join(", "));
